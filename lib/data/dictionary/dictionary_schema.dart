/// The dictionary database's schema, as one declaration.
///
/// ## Why it lives in `lib/` and not in `tool/`
///
/// The build tool that writes `assets/dictionary/en_ar.db` and the tests that
/// read it have to agree, and there is exactly one place they can both import.
/// A schema written twice is a schema that will differ, and the difference
/// would show up as a database whose columns do not match what the code asks
/// for - at query time, on a phone, with no test.
///
/// ## Why the names are fixed
///
/// `entries`, `senses`, `examples`, `trigrams`, `meta` and the five columns of
/// each are the brief's, verbatim. They are what the tests name, so they are
/// what a rename would break.
///
/// ## The database is a separate file, on purpose
///
/// `lib/data/database.dart` holds the user's data - packs, progress, favourites,
/// stats, settings - and it is written to. This file is read-only reference and
/// it ships in `assets/` beside the fonts and the wallpapers. Two consequences,
/// both deliberate:
///
///  * `databaseSchemaVersion` stays at **2**. A v1 to v2 migration has already
///    shipped this session; a second, unrelated bump for a read-only reference
///    table would be the version-counter collision fixed in `898ec02` and
///    `ff7932c` all over again.
///  * A backup exports favourites and progress, not 25 MB of dictionary.
///    `BackupDocument` never mentions this file, so it cannot.
///
/// **There is no migration here and none will be written.** The file is
/// regenerated by `tool/build_dictionary_db.dart` and replaced wholesale; if
/// [dictionarySchemaVersion] ever changes, the artefact is rebuilt, not migrated.
library;

/// The schema version stamped into `PRAGMA user_version` of the shipped file.
///
/// `1` means "the schema in this file". The database is opened read-only and
/// the version is verified on open, so a stale artefact left over from an older
/// checkout fails loudly at start-up instead of answering queries with columns
/// that are not there.
const int dictionarySchemaVersion = 1;

/// Where the finished database is shipped inside the app bundle.
const String dictionaryAssetPath = 'assets/dictionary/en_ar.db';

/// Where the morphology table is shipped inside the app bundle.
///
/// **JSON, not a table** (ruling D): 8.5 KB, read once at start-up, and it would
/// need a query on nearly every keystroke if it were in SQLite.
const String morphologyAssetPath = 'assets/dictionary/en_morphology.json';

/// The `CREATE TABLE` statements, in creation order.
///
/// **Written without a trailing semicolon on purpose.** SQLite stores the text
/// of a prepared statement minus its terminator in `sqlite_master.sql`, so these
/// strings compare equal to what a reader finds on disk. `test/data/dictionary/dictionary_schema_test.dart`
/// asserts that equality - which is the test that stops a stale or hand-edited
/// artefact shipping.
const Map<String, String> dictionaryTables = <String, String>{
  'entries': '''
CREATE TABLE entries (
  id      INTEGER PRIMARY KEY,
  word    TEXT NOT NULL,
  norm    TEXT NOT NULL UNIQUE,
  ipa     TEXT,
  has_ar  INTEGER NOT NULL
)''',
  'senses': '''
CREATE TABLE senses (
  id        INTEGER PRIMARY KEY,
  entry_id  INTEGER NOT NULL,
  pos       TEXT,
  ar        TEXT,
  norm_ar   TEXT,
  en        TEXT
)''',
  'examples': '''
CREATE TABLE examples (
  id        INTEGER PRIMARY KEY,
  sense_id  INTEGER NOT NULL,
  text      TEXT NOT NULL
)''',
  'trigrams': '''
CREATE TABLE trigrams (
  t          TEXT NOT NULL,
  entry_id   INTEGER NOT NULL
)''',
  'meta': '''
CREATE TABLE meta (
  k TEXT PRIMARY KEY NOT NULL,
  v TEXT NOT NULL
)''',
};

/// The indices, in creation order.
///
/// No `FOREIGN KEY`s, deliberately. The file is opened read-only, never
/// migrated and never partially written - `tool/build_dictionary_db.dart`
/// writes it in one transaction into a file that did not exist - so a
/// constraint would be checked on every build and could never fire at runtime.
/// The app database gets them because it *is* written to at runtime; this one
/// is not.
const Map<String, String> dictionaryIndices = <String, String>{
  'idx_senses_entry_id': 'CREATE INDEX idx_senses_entry_id ON senses (entry_id)',
  'idx_senses_norm_ar': 'CREATE INDEX idx_senses_norm_ar ON senses (norm_ar)',
  'idx_examples_sense_id':
      'CREATE INDEX idx_examples_sense_id ON examples (sense_id)',
  'idx_trigrams_t': 'CREATE INDEX idx_trigrams_t ON trigrams (t)',
};

/// Every object the schema creates, in the order `sqlite_master` should list
/// them. `entries.norm` carries its own `UNIQUE` constraint and so needs no
/// separate index statement.
const List<String> dictionarySchemaObjects = <String>[
