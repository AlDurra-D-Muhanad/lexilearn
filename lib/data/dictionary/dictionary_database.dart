/// Thrown when the database on disk is not the one this build of the app
/// expects.
///
/// **A loud failure, on purpose.** The dictionary is a committed build
/// artefact, and a stale one is a real failure mode: a schema change that
/// nobody rebuilt against would otherwise show up as a query against a column
/// that is not there, on a phone, with no test. Failing at open time names the
/// problem in one line.
class DictionarySchemaMismatch implements Exception {
  const DictionarySchemaMismatch(this.message);

  final String message;

  @override
  String toString() => 'DictionarySchemaMismatch: $message';
}

/// Opens the dictionary database **read-only**.
///
/// **Read-only, and the file is not the app's database.** `lib/data/database.dart`
/// holds the user's data and is written to; this file is reference material
/// shipped inside the APK. Two consequences, both deliberate:
///
///  * `databaseSchemaVersion` stays at 2. A second, unrelated bump for a
///    read-only reference table would be the version-counter collision fixed in
///    `898ec02` and `ff7932c` all over again.
///  * A backup exports favourites and progress, never 25 MB of dictionary.
///
/// **No migration, here or anywhere.** The artefact is regenerated by
/// `tool/build_dictionary_db.dart` and replaced wholesale. The version stamped
/// in `PRAGMA user_version` is checked on open, and a mismatch is an error
/// rather than an upgrade.
Future<Database> openDictionaryDatabase({
  required DatabaseFactory factory,
  required String path,
  bool singleInstance = true,
}) {
  return factory.openDatabase(
    path,
    options: OpenDatabaseOptions(
      readOnly: true,
      singleInstance: singleInstance,
      onConfigure: _onConfigure,
    ),
  );
}

Future<void> _onConfigure(Database db) async {
  final rows = await db.rawQuery('PRAGMA user_version');
  final version = rows.first.values.first! as int;
  if (version != dictionarySchemaVersion) {
    throw DictionarySchemaMismatch(
      'the dictionary database at this path is schema version $version, '
      'and this build of the app speaks version $dictionarySchemaVersion. '
      'Regenerate it with `dart run tool/build_dictionary_db.dart`.',
    );
  }
}

/// Copies the dictionary out of the app bundle and onto the device.
///
/// **Why a copy at all.** An asset inside an APK is a compressed stream; SQLite
/// needs a real file it can `mmap` and seek in. The asset is copied once, on
/// first run, and the copy is reused after that.
///
/// **The copy is skipped when it is already correct.** The expected size comes
/// from `dictionary_artifact.dart`, which the build tool writes from the file
/// it just produced - so the check is against the artefact itself and not
/// against a number somebody typed. A 26 MB copy on every launch would be
/// indefensible; a copy only when the file is missing or the wrong size is
/// one copy per app version.
Future<String> installDictionaryAsset({
  required Future<ByteData> Function(String key) load,
  required String targetPath,
  int expectedBytes = dictionaryArtifactBytes,
}) async {
  final target = File(targetPath);
  if (target.existsSync() && target.lengthSync() == expectedBytes) {
    return targetPath;
  }
  await target.parent.create(recursive: true);
  final data = await load(dictionaryAssetPath);
  final bytes = data.buffer.asUint8List(
    data.offsetInBytes,
    data.lengthInBytes,
  );
  if (bytes.length != expectedBytes) {
    throw DictionarySchemaMismatch(
      'the bundled dictionary asset is ${bytes.length} bytes, and the build '
      'recorded $expectedBytes. The bundle and the code are from different '
      'builds.',
    );
  }
  await target.writeAsBytes(bytes, flush: true);
  return targetPath;
}

/// Reads the morphology table out of the app bundle.
///
/// **JSON, not a table** (ruling D): 8.5 KB, read once, and it would need a
/// query on nearly every keystroke if it were in SQLite.
Future<MorphologyTable> loadMorphologyTable({
  required Future<String> Function(String key) load,
}) async {
  return MorphologyTable.parse(await load(morphologyAssetPath));
}

/// Opens the dictionary and hands back an engine over it.
///
/// The one call an app makes at start-up. **It parses no JSON** - the 12 MB
/// source dictionary was turned into the SQLite artefact once, offline, by
/// `tool/build_dictionary_db.dart`.
Future<DictionaryEngine> openDictionaryEngine({
  required DatabaseFactory factory,
  required String path,
  required MorphologyTable morphology,
  bool singleInstance = true,
}) async {
  final db = await openDictionaryDatabase(
    factory: factory,
    path: path,
    singleInstance: singleInstance,
  );
  return DictionaryEngine(
    store: DictionaryStore(db),
    morphology: morphology,
  );
}
